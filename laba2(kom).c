#define _CRT_SECURE_NO_WARNINGS    // отключаем предупреждения Visual Studio
#define K 2                        // K = 2 (ожидаем 2 аргумента: программа + файл)
#include <stdio.h>                 // для printf, scanf, fopen, fscanf, fseek, ftell
#include <locale.h>                // для setlocale (русские буквы в консоли)

int main(int argc, char* argv[])   // argc = кол-во аргументов, argv = массив аргументов
{
    FILE* in;                      // указатель на входной файл
    char ch;                       // сюда читаем по одному символу
    long posB, posE;               // позиция начала (B=Begin) и конца (E=End) предложения
    long pos;                      // временная позиция (для запоминания)
    int n;                         // нужное количество слов в предложении
    int words;                     // счётчик слов в текущем предложении
    int inWord;                    // флаг: 1 если сейчас внутри слова, 0 если нет
    long i;                        // переменная для цикла for

    setlocale(0, "");              // включаем локаль системы (для русских букв)

    if (argc != K)                 // если количество аргументов не равно 2
    {
        printf("Неверное количество аргументов");
        return 1;                  // выходим с кодом ошибки 1
    }

    in = fopen(argv[1], "r");      // открываем файл (имя в argv[1]) для чтения
    if (in == NULL)                // если файл не открылся
    {
        printf("Файл %s не найден", argv[1]);
        return 2;                  // выходим с кодом ошибки 2
    }

    printf("Введите количество слов: ");
    scanf("%d", &n);               // считываем число от пользователя в переменную n

    posB = ftell(in);              // запоминаем позицию начала первого предложения (= 0)
    words = 0;                     // слов пока не нашли
    inWord = 0;                    // мы НЕ внутри слова

    while (fscanf(in, "%c", &ch) == 1)   // пока удаётся читать символ из файла
    {
        if ((ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z'))   // если символ — буква
        {
            if (inWord == 0)       // если до этого мы НЕ были в слове
            {
                inWord = 1;        // теперь мы ВНУТРИ слова
                words++;           // нашли новое слово, увеличиваем счётчик
            }
        }
        else                       // если символ НЕ буква (пробел, точка, цифра и т.д.)
        {
            inWord = 0;            // мы вышли из слова

            if (ch == '.' || ch == '?' || ch == '!')   // если это конец предложения
            {
                posE = ftell(in);  // запоминаем позицию конца предложения

                if (words == n)    // если количество слов = заданному
                {
                    pos = posE;                    // запомнили текущую позицию (например 20)
                    fseek(in, posB, SEEK_SET);     // перенесли курсор на posB (например 7)
                    for (i = posB; i < posE; i++)  // от начала до конца предложения
                    {
                        fscanf(in, "%c", &ch);     // читаем по одному символу
                        printf("%c", ch);          // и печатаем его
                    }
                    printf("\n");                  // переход на новую строку
                    fseek(in, pos, SEEK_SET);      // вернули курсор обратно на 20
                }

                posB = posE;       // начало нового предложения = конец прошлого
                words = 0;         // сбрасываем счётчик слов
                inWord = 0;        // не в слове
            }
        }
    }

    _fcloseall();                  // закрываем все открытые файлы
    return 0;                      // программа завершилась успешно
}
